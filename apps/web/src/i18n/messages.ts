/** Arabic counted nouns: 1 → singular, 2 → dual, 3-10 → plural, 11+ → singular with number. */
function arabicCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

